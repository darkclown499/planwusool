    public function run(): void
    {
        if (Country::count() === 0) {
            $this->command->info('Seeding world countries...');
            $this->call(WorldCountriesSeeder::class);
        }

        $this->arabicizeNames();
        $this->seedGeography();

        $this->command->info('Regional countries seeded: ' . Country::count() . ' countries, ' . State::count() . ' states, ' . City::count() . ' cities.');
    }

    private function arabicizeNames(): void
    {
        foreach (self::ARABIC_NAMES as $code => $name) {
            Country::updateOrCreate(
                ['code' => $code],
                ['name' => $name, 'status' => true]
            );
        }
    }

    private function seedGeography(): void
    {
        foreach ($this->geoData() as $code => $states) {
            $country = Country::where('code', $code)->first();
            if (!$country) {
                $this->command->warn("Country $code not found, skipping geography.");
                continue;
            }

            foreach ($states as $stateName => $cities) {
                $state = State::firstOrCreate(
                    ['country_id' => $country->id, 'name' => $stateName],
                    ['status' => true]
                );

                foreach ($cities as $cityName) {
                    City::firstOrCreate(
                        ['state_id' => $state->id, 'name' => $cityName],
                        ['status' => true]
                    );
                }
            }
        }
    }

