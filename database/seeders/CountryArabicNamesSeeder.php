    public function run(): void
    {
        $updated = 0;
        foreach (self::ARABIC_NAMES as $code => $name) {
            $country = Country::where('code', $code)->first();
            if ($country) {
                $country->update(['name' => $name]);
                $updated++;
            } else {
                $this->command->warn("Country with code $code not found, skipping.");
            }
        }
        $this->command->info("Updated $updated countries with Arabic names.");
    }
